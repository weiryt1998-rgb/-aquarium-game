/**
 * ของตกแต่งตู้ปลา
 *
 * ── การใส่โมเดล .glb ภายหลัง ──
 * วางไฟล์ที่ public/models/decor/<id>.glb  เช่น castle.glb
 * หรือใช้ไฟล์กลางตามหมวด: plant.glb (พืชน้ำทุกชนิด), rock.glb (หินทุกชนิด)
 *   - จุดหมุน (origin) ควรอยู่ที่ฐานของโมเดล
 *   - เกมจะปรับให้สูงเท่ากับ height อัตโนมัติ (หรือกว้างเท่า size ถ้า fit: 'width')
 *
 * placeholder = ชนิดของโมเดลชั่วคราวที่สร้างด้วยโค้ด
 * radius      = รัศมีฐาน ใช้ตอนจัดวางและให้ปลาว่ายหลบ
 * obstacle    = ปลาว่ายหลบหรือไม่ (พืชน้ำปลาว่ายผ่านได้)
 * happiness   = คะแนนความสุขที่ปลาได้รับ
 * cleanBonus  = ช่วยลดความสกปรกของน้ำ (0..1)
 * maxPerTank  = วางได้สูงสุดกี่ชิ้นต่อตู้ (ไม่ระบุ = ไม่จำกัด)
 * pearl       = ผลิตไข่มุกเป็นระยะ (ดู shared/economy.js → pearlReadyAt)
 * model.fallback = false → ไม่ใช้ไฟล์กลางของหมวด (plant.glb / rock.glb) แทน เพราะรูปทรงเฉพาะตัว
 */

